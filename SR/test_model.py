import torch

from models.edsr import EDSR


# ------------------------------------------------------------
# Device
# ------------------------------------------------------------

device = torch.device(
    "cuda" if torch.cuda.is_available() else "cpu"
)

print("Device:", device)


# ------------------------------------------------------------
# Create model
# ------------------------------------------------------------

model = EDSR(
    in_channels=3,
    out_channels=3,
    channels=64,
    num_blocks=8
).to(device)


# ------------------------------------------------------------
# Random input
# ------------------------------------------------------------

x = torch.randn(
    1,
    3,
    256,
    256
).to(device)


# ------------------------------------------------------------
# Forward pass
# ------------------------------------------------------------

with torch.no_grad():

    y = model(x)


# ------------------------------------------------------------
# Print shapes
# ------------------------------------------------------------

print("Input :", x.shape)
print("Output:", y.shape)


# ------------------------------------------------------------
# Check
# ------------------------------------------------------------

assert y.shape == (
    1,
    3,
    256,
    256
)

print()
print("SR model shape test PASSED!")